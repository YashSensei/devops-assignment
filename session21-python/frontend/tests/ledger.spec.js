import {test,expect} from '@playwright/test';
import {join} from 'node:path';

// Local reruns must never overwrite committed historical evidence.
const capture = name => join(process.env.EVIDENCE_DIR || 'test-results/evidence', name);

test('equipment lifecycle, loan rules, persistence, filters, and mobile layout',async({page})=>{
  const tag='E2E-'+Date.now();
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'A place for every kit.'})).toBeVisible();
  await page.getByRole('button',{name:'＋ Add equipment',exact:true}).click();
  await page.getByLabel('Asset tag',{exact:true}).fill(tag);
  await page.getByLabel('Equipment name',{exact:true}).fill('Field recorder');
  await page.getByLabel('Category',{exact:true}).fill('Audio');
  await page.getByLabel('Notes',{exact:true}).fill('Automated test equipment. Keep dry; return with cable.');
  await page.getByRole('button',{name:'Save equipment',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Equipment saved');
  await page.getByRole('searchbox').fill(tag);
  await page.getByRole('button',{name:'Edit Field recorder',exact:true}).click();
  await page.getByLabel('Equipment name',{exact:true}).fill('Field recorder + cable');
  await page.getByRole('button',{name:'Save equipment',exact:true}).click();
  await expect(page.getByText('Field recorder + cable',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('searchbox').fill(tag);
  await expect(page.getByText('Field recorder + cable',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Check out ↗',exact:true}).click();
  await page.getByLabel('Borrower name').fill('Demo student');
  await page.getByLabel('Purpose').fill('Sound recording workshop');
  await page.getByRole('button',{name:'Confirm checkout',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Loan recorded');
  await expect(page.getByRole('button',{name:'Check out ↗',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:/Loan register/}).click();
  await page.getByRole('searchbox').fill(tag);
  await expect(page.getByText('Sound recording workshop',{exact:true})).toBeVisible();
  await page.screenshot({path:capture('desktop-loan.png'),fullPage:true});
  await page.getByRole('button',{name:'Record return ↙',exact:true}).click();
  await page.getByLabel('Returned condition').selectOption('maintenance');
  await page.getByRole('button',{name:'Save return',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Return recorded');
  await page.getByRole('combobox',{name:'Filter status'}).selectOption('returned');
  await expect(page.getByText('Field recorder + cable',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Equipment library/}).click();
  await page.getByRole('searchbox').fill(tag);
  await page.getByRole('combobox',{name:'Filter status'}).selectOption('maintenance');
  await expect(page.getByText('Field recorder + cable',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Delete Field recorder + cable',exact:true}).click();
  await page.getByRole('button',{name:'Delete equipment',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('loan history');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await expect(page.getByRole('button',{name:'＋ Add equipment',exact:true})).toBeVisible();
  await page.screenshot({path:capture('mobile-library.png'),fullPage:true});
  const bounds=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
  expect(bounds.scroll).toBeLessThanOrEqual(bounds.viewport);
  await page.getByRole('button',{name:'＋ Add equipment',exact:true}).click();
  await page.getByLabel('Asset tag',{exact:true}).fill(tag+'-TEMP');
  await page.getByLabel('Equipment name',{exact:true}).fill('Temporary tripod');
  await page.getByLabel('Category',{exact:true}).fill('Support');
  await page.getByRole('button',{name:'Save equipment',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Equipment saved');
  await page.getByRole('searchbox').fill(tag+'-TEMP');
  await page.getByRole('button',{name:'Delete Temporary tripod',exact:true}).click();
  await page.getByRole('button',{name:'Delete equipment',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Unused equipment deleted');
  await expect(page.getByText('Temporary tripod',{exact:true})).toHaveCount(0);
  if(process.env.METRICS_URL){
    const metrics=await page.context().newPage();
    await metrics.goto(process.env.METRICS_URL);
    await expect(metrics.locator('body')).toContainText('kitledger_http_requests_total');
    await metrics.screenshot({path:capture('metrics.png'),fullPage:true});
  }
});
